"""The pizza recipe becomes De Morgan's first law, then two matching stencils."""
from manim_scenes.story_world import *
class Scene10DeMorganOne(ThreeDScene):
    def construct(self): play_scene(self)

def play_scene(scene):
    t,head=start(scene,'10','Two recipes for the same pizza')
    left=pizza(1.65,[-3.5,0,0]); right=pizza(1.65,[3.5,0,0])
    tags=VGroup(label('Remove dairy OR meat',34,cfg.PURPLE).move_to([-3.5,2.3,0]),label('Not dairy AND not meat',34,cfg.GREEN).move_to([3.5,2.3,0]))
    scene.play(FadeIn(left,right,tags),run_time=1.2)
    cue(scene,t,16)
    clear(scene,head)
    stage=venn(); scene.play(FadeIn(stage),run_time=.8)
    replace_text(scene,head,heading('First recipe: exclude the whole union'),run_time=.6)
    united=mask(stage,'union',cfg.RED)
    scene.play(FadeIn(united),run_time=.8)
    cap=change(scene,None,'A ∪ B',cfg.RED); cue(scene,t,27)
    outside=mask(stage,'neither',cfg.PURPLE)
    scene.play(FadeOut(cap),run_time=.2)
    scene.play(FadeOut(united),FadeIn(outside),run_time=.8)
    cap=change(scene,None,'(A ∪ B)ᶜ',cfg.PURPLE); cue(scene,t,39)
    scene.play(FadeOut(outside,cap),run_time=.2)
    replace_text(scene,head,heading('Second recipe: pass both exclusions'),run_time=.5)
    not_a=mask(stage,'not_a',cfg.BLUE); not_b=mask(stage,'not_b',cfg.ORANGE)
    scene.play(FadeIn(not_a),run_time=.8)
    cap=change(scene,None,'Aᶜ  ·  outside A',cfg.BLUE); cue(scene,t,49)
    scene.play(FadeOut(cap),run_time=.2)
    scene.play(FadeOut(not_a),FadeIn(not_b),run_time=.6)
    cap=change(scene,None,'Bᶜ  ·  outside B',cfg.ORANGE); cue(scene,t,59)
    intersection=stage.intersect_regions('not_a','not_b',cfg.GREEN,fill_opacity=.5).set_z_index(1)
    scene.play(FadeOut(cap),run_time=.2)
    scene.play(FadeOut(not_b),FadeIn(intersection),run_time=.8)
    cap=change(scene,None,'Aᶜ ∩ Bᶜ  ·  outside both',cfg.GREEN); cue(scene,t,71)
    clear(scene,head)
    replace_text(scene,head,heading('Two regions. One answer.'),run_time=.6)
    sheets=VGroup()
    for x,z,color,region in [(-3.2,0,cfg.PURPLE,outside),(3.2,-1.5,cfg.GREEN,intersection)]:
        sheet=Rectangle(width=5.6,height=2.8,stroke_color=color,stroke_width=3,fill_color=cfg.PANEL_2,fill_opacity=.2)
        patch=region.copy().scale(.43).move_to(sheet).set_z_index(0)
        sheets.add(VGroup(sheet,patch).move_to([x,-.2,z]))
    scene.play(FadeIn(sheets),run_time=1)
    move_camera(scene,phi=42*DEGREES,theta=-84*DEGREES,run_time=2)
    cue(scene,t,82)
    scene.play(sheets[0].animate.shift(RIGHT*3.2),sheets[1].animate.shift(LEFT*3.2+OUT*1.5),run_time=2)
    cap=change(scene,None,'The same selection',cfg.GREEN)
    cue(scene,t,94)
    clear(scene,head)
    scene.set_camera_orientation(phi=0,theta=-PI/2,zoom=1)
    replace_text(scene,head,heading('De Morgan’s first law'),run_time=.6)
    law=formula('(A ∪ B)ᶜ = Aᶜ ∩ Bᶜ',62,cfg.GOLD).move_to([0,1.3,0])
    pie=pizza(1.25,[0,-1,0]); scene.play(FadeIn(law,pie),run_time=1)
    cap=change(scene,None,'Neither means outside both',cfg.GREEN)
    cue(scene,t,111)
    cap=change(scene,cap,'NOT (p OR q)  =  (NOT p) AND (NOT q)',cfg.CYAN)
    cue(scene,t,123.5)
    math_beat(scene,head,'Why the first law holds',['x\\in(A\\cup B)^{c}', '\\Longleftrightarrow\\;x\\notin A\\;\\land\\;x\\notin B', '\\Longleftrightarrow\\;x\\in A^{c}\\cap B^{c}'],'The same test works for every x in U')
    cue(scene,t,137.5)
    end_scene(scene,t,cfg.SCENE_DURATIONS['10']); finish(scene)
