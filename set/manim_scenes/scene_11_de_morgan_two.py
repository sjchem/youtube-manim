"""A toy gate blocks exactly the red squares: not both is an inclusive OR."""
from manim_scenes.story_world import *
class Scene11DeMorganTwo(Scene):
    def construct(self): play_scene(self)

def play_scene(scene):
    t,head=start(scene,'11','A toy gate with one rule')
    toys=VGroup(Square(side_length=1.15,fill_color=cfg.RED,fill_opacity=1,stroke_width=0),Circle(radius=.6,fill_color=cfg.RED,fill_opacity=1,stroke_width=0),Square(side_length=1.15,fill_color=cfg.BLUE,fill_opacity=1,stroke_width=0),Circle(radius=.6,fill_color=cfg.BLUE,fill_opacity=1,stroke_width=0)).arrange(RIGHT,buff=1.5).move_to([0,.35,0])
    scene.play(LaggedStart(*[GrowFromCenter(m) for m in toys],lag_ratio=.15),run_time=1.5)
    cap=change(scene,None,'BLOCK: red AND square',cfg.RED)
    cue(scene,t,17)
    cross=label('×',48,cfg.WHITE).move_to(toys[0])
    marks=VGroup(*[checkmark(m.get_center()+DOWN*1.4) for m in toys[1:]])
    scene.play(FadeIn(cross,marks),toys[0].animate.set_opacity(.4),run_time=1)
    replace_text(scene,head,heading('Which toys are allowed through?'),run_time=.6)
    cue(scene,t,30)
    cap=change(scene,cap,'PASS: not red OR not square',cfg.GREEN)
    scene.play(Indicate(toys[1],scale_factor=1.12),run_time=.8)
    cue(scene,t,39)
    scene.play(Indicate(toys[2],scale_factor=1.12),run_time=.8)
    cue(scene,t,47)
    scene.play(Indicate(toys[3],scale_factor=1.12),run_time=.8)
    clear(scene,head)
    replace_text(scene,head,heading('De Morgan’s second law'),run_time=.6)
    stage=venn('Red','Square'); scene.play(FadeIn(stage),run_time=.9)
    lens=mask(stage,'both',cfg.RED); scene.play(FadeIn(lens),run_time=.7)
    cap=change(scene,None,'R ∩ S  ·  the blocked toys',cfg.RED)
    cue(scene,t,59)
    result=mask(stage,'not_both',cfg.GREEN)
    scene.play(FadeOut(cap),run_time=.2)
    scene.play(FadeOut(lens),FadeIn(result),run_time=.6)
    cap=change(scene,None,'(R ∩ S)ᶜ = Rᶜ ∪ Sᶜ',cfg.GREEN)
    cue(scene,t,72)
    cap=change(scene,cap,'NOT both  =  at least one NOT',cfg.GOLD)
    cue(scene,t,83.5)
    math_beat(scene,head,'Why the second law holds',['x\\notin R\\cap S\\;\\Longleftrightarrow\\;(x\\notin R)\\lor(x\\notin S)', '(R\\cap S)^{c}=R^{c}\\cup S^{c}'],'Not both allows one condition to hold')
    cue(scene,t,100.5)
    end_scene(scene,t,cfg.SCENE_DURATIONS['11']); finish(scene)
