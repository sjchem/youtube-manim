"""The kitchen inventory makes the universe and its complement tangible."""
from manim_scenes.story_world import *
class Scene08Complement(ThreeDScene):
    def construct(self): play_scene(self)

def play_scene(scene):
    t,head=start(scene,'08','What is left in this kitchen?')
    shelf=tray(12.6,4.4,cfg.CYAN,[0,.1,0])
    available=row(('mozzarella','ricotta','mushroom','olive','onion','pepper'),1.2,(0,.1,0),.8)
    scene.play(FadeIn(shelf,available),run_time=1.2)
    cap=change(scene,None,'U = six available toppings')
    cue(scene,t,15)
    dairy=tray(3.5,2.5,cfg.BLUE,[-4.1,.1,0],'Dairy: D')
    scene.play(FadeIn(dairy),available[0].animate.move_to([-4.8,.1,0]),available[1].animate.move_to([-3.4,.1,0]),*[m.animate.move_to([-.6+i*1.75,.1,0]) for i,m in enumerate(available[2:])],run_time=1.2)
    cap=change(scene,cap,'Keep the non-dairy choices',cfg.PURPLE)
    cue(scene,t,31)
    scene.play(available[0].animate.set_opacity(.25),available[1].animate.set_opacity(.25),run_time=.7)
    cap=change(scene,cap,'Dᶜ = {mushroom, olive, onion, pepper}',cfg.PURPLE)
    cue(scene,t,44)
    clear(scene,head)
    replace_text(scene,head,heading('“Not dairy”… from which collection?'),run_time=.5)
    slab=Prism(dimensions=[9.6,4,.25],fill_color=cfg.PANEL_2,fill_opacity=1,stroke_color=cfg.CYAN,stroke_width=2)
    produce=row(('mushroom','olive','onion','pepper'),1.1,(0,0,.17),1).set_z_index(0)
    scene.play(FadeIn(slab,produce),run_time=1)
    move_camera(scene,phi=48*DEGREES,theta=-80*DEGREES,run_time=2)
    cue(scene,t,57)
    extras=row(('apple','banana','pizza'),1.1,(0,4.1,.2),1.1).set_z_index(0)
    scene.play(FadeIn(extras),run_time=.8)
    move_camera(scene,zoom=.7,run_time=2)
    cap=change(scene,None,'Other food lies outside U')
    cue(scene,t,69)
    clear(scene,head)
    scene.set_camera_orientation(phi=0,theta=-PI/2,zoom=1)
    replace_text(scene,head,heading('Change the universe, change the answer'),run_time=.5)
    only=tray(7,3,cfg.BLUE,[0,0,0],'U = the dairy toppings')
    cheese=row(('mozzarella','ricotta'),1.5,(0,0,0),1.1)
    scene.play(FadeIn(only,cheese),run_time=.8)
    cap=change(scene,None,'If U = D, then Dᶜ = ∅',cfg.PURPLE)
    cue(scene,t,84)
    cap=change(scene,cap,'Complement stays inside U')
    cue(scene,t,93.5)
    math_beat(scene,head,'The complement rule',['D^{c}=U\\setminus D', 'x\\in D^{c}\\;\\Longleftrightarrow\\;(x\\in U)\\land(x\\notin D)'],'Outside D, but still inside U')
    cue(scene,t,110.5)
    end_scene(scene,t,cfg.SCENE_DURATIONS['08']); finish(scene)
