"""A fruit basket gives membership, order, and repetition a physical meaning."""
from manim_scenes.story_world import *

class Scene02WhatIsASet(Scene):
    def construct(self): play_scene(self)

def play_scene(scene):
    t,head=start(scene,'02','Pack a fruit basket')
    surface=counter(); scene.add(surface)
    objects=row(('apple','banana','pizza','strawberry','carrot','grapes'),1.15,(0,.5,0),.8)
    scene.play(LaggedStart(*[FadeIn(m,shift=DOWN*.4) for m in objects],lag_ratio=.15),run_time=2)
    cue(scene,t,12)
    basket_mob=basket(4.7,2.1,[-3.3,-.6,0])
    scene.play(FadeIn(basket_mob),run_time=.8)
    seats=[[-4.2,.05,0],[-2.45,.05,0],[-4.2,-1.12,0],[-2.45,-1.12,0]]
    selected=[objects[i] for i in (0,1,3,5)]
    scene.play(*[m.animate.scale(.8).move_to(p) for m,p in zip(selected,seats)],objects[2].animate.move_to([3.0,.9,0]),objects[4].animate.move_to([5.2,.9,0]),run_time=1.7)
    tag=label('Fruit',30,cfg.GOLD).move_to([-3.3,2.3,0]); scene.play(FadeIn(tag),run_time=.6)
    cap=change(scene,None,'A rule tells us what belongs')
    cue(scene,t,27)
    roster=formula('A = {apple, banana, strawberry, grapes}',40).move_to([0,-3.78,0])
    scene.play(FadeOut(cap),run_time=.3)
    scene.play(FadeIn(roster),run_time=.4); cap=None
    cue(scene,t,41)
    yes=formula('apple ∈ A',42,cfg.GREEN).move_to([3.8,-.65,0])
    scene.play(FadeOut(roster),FadeIn(yes),Indicate(objects[0],scale_factor=1.12),run_time=1)
    cap=change(scene,None,'∈  means “belongs to”',cfg.GREEN)
    cue(scene,t,53)
    no=formula('pizza ∉ A',42,cfg.RED).move_to(yes)
    replace_text(scene,yes,no,run_time=.6)
    scene.play(Indicate(objects[2],scale_factor=1.12),run_time=.4)
    cap=change(scene,cap,'∉  means “does not belong”',cfg.RED)
    cue(scene,t,64)
    clear(scene,head)
    replace_text(scene,head,heading('Does order matter?'),run_time=.5)
    trio=row(('apple','banana','grapes'),1.6,(0,.5,0),1.35)
    scene.play(FadeIn(trio),run_time=.8)
    before=[m.get_center().copy() for m in trio]
    scene.play(*[m.animate.move_to(before[(i+1)%3]) for i,m in enumerate(trio)],path_arc=PI/2,run_time=2)
    cap=change(scene,None,'Same members. Same set.',cfg.GREEN)
    cue(scene,t,83)
    clear(scene,head)
    replace_text(scene,head,heading('Does a repeated name add a member?'),run_time=.5)
    repeated=row(('apple','apple','apple','banana'),1.3,(0,.3,0),1)
    scene.play(FadeIn(repeated),run_time=.8)
    cap=change(scene,None,'These apples repeat the same named element')
    cue(scene,t,99)
    scene.play(FadeOut(repeated[1],repeated[2],shift=UP*.3),repeated[0].animate.move_to([-1.3,.3,0]),repeated[3].animate.move_to([1.3,.3,0]),run_time=1.4)
    cap=change(scene,cap,'{apple, banana}  →  2 distinct members',cfg.GREEN)
    cue(scene,t,116)
    math_beat(scene,head,'What the basket means',['A=\\{\\text{apple},\\text{banana},\\text{strawberry},\\text{grapes}\\}'],'x ∈ A means x passes the fruit rule')
    cue(scene,t,126.5)
    clear(scene,head)
    replace_text(scene,head,heading('Can one collection fit inside another?'),run_time=.7)
    small=tray(2.2,1.6,cfg.GOLD,[-3,0,0]).set_z_index(3); large=tray(5.8,3.1,cfg.BLUE,[2,0,0])
    scene.play(FadeIn(small,large),run_time=.8)
    scene.play(small.animate.move_to(large.base),run_time=1.6)
    cue(scene,t,137.5)
    end_scene(scene,t,cfg.SCENE_DURATIONS['02']); finish(scene)
