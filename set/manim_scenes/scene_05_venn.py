"""The platypus arrives at a park whose two habitats need to overlap."""
from manim_scenes.story_world import *
class Scene05Venn(Scene):
    def construct(self): play_scene(self)

def play_scene(scene):
    t,head=start(scene,'05','A visitor who belongs in both places')
    left=habitat(4.5,4,[-3.6,-.2,0],cfg.BLUE)
    right=habitat(4.5,4,[3.6,-.2,0],cfg.ORANGE)
    tags=VGroup(label('Mammals',36,cfg.BLUE).move_to([-3.6,2.3,0]),label('Egg-layers',36,cfg.ORANGE).move_to([3.6,2.3,0]))
    animals=VGroup(food('dog',1.1,[-4.2,.45,0]),food('whale',1.15,[-3,-.8,0]),food('chicken',1.1,[3,.45,0]),food('snake',1.1,[4.2,-.8,0]))
    scene.play(FadeIn(left,right,tags),FadeIn(animals),run_time=1.5)
    cap=change(scene,None,'Two properties, two habitats')
    cue(scene,t,18)
    platy=food('platypus',1.7,[0,.65,0]); name=label('Platypus',34,cfg.GOLD).move_to([0,-.2,0])
    scene.play(FadeIn(platy,shift=DOWN*.4),FadeIn(name),run_time=1)
    facts=VGroup(label('Mammal',32,cfg.BLUE).move_to([0,-1,0]),label('Lays eggs',32,cfg.ORANGE).move_to([0,-1.65,0]))
    scene.play(FadeIn(facts[0]),run_time=.6); cue(scene,t,29)
    scene.play(FadeIn(facts[1]),run_time=.6)
    scene.play(FadeOut(cap),run_time=.2)
    replace_text(scene,head,heading('Where should the platypus go?'),run_time=.5)
    countdown(scene); cue(scene,t,42)
    scene.play(FadeOut(facts,name),left.animate.shift(RIGHT*2.35),right.animate.shift(LEFT*2.35),tags[0].animate.shift(RIGHT*1.5),tags[1].animate.shift(LEFT*1.5),animals[0].animate.move_to([-2.6,.6,0]),animals[1].animate.move_to([-2.6,-.85,0]),animals[2].animate.move_to([2.6,.6,0]),animals[3].animate.move_to([2.6,-.85,0]),platy.animate.move_to([0,-.2,0]).scale(.8),run_time=2)
    lens=Intersection(left[0],right[0],fill_color=cfg.GOLD,fill_opacity=.45,stroke_width=0).set_z_index(1)
    scene.play(FadeIn(lens),run_time=.8)
    cap=change(scene,None,'Mammal AND egg-layer',cfg.GOLD)
    cue(scene,t,60)
    replace_text(scene,head,heading('The overlap tells us both rules are true'),run_time=.6)
    math=formula('platypus ∈ M ∩ E',50).move_to([0,-3.78,0])
    scene.play(FadeOut(cap),run_time=.3)
    scene.play(FadeIn(math),run_time=.4)
    cue(scene,t,74)
    replace_text(scene,head,heading('One animal. Two memberships.'),run_time=.5)
    scene.play(Indicate(platy,scale_factor=1.12),run_time=.4)
    cue(scene,t,83.5)
    math_beat(scene,head,'The intersection rule',['x\\in M\\cap E\\;\\Longleftrightarrow\\;(x\\in M)\\land(x\\in E)'],'An overlap means both memberships hold')
    cue(scene,t,98.5)
    end_scene(scene,t,cfg.SCENE_DURATIONS['05']); finish(scene)
