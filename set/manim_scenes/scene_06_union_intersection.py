"""Two pizza orders: collect either order, then find what both friends chose."""
from manim_scenes.story_world import *
class Scene06UnionIntersection(Scene):
    def construct(self): play_scene(self)

def play_scene(scene):
    t,head=start(scene,'06','Two friends place two orders')
    a=tray(4.7,2.4,cfg.BLUE,[-3.5,.1,0],'Order A')
    b=tray(4.7,2.4,cfg.ORANGE,[3.5,.1,0],'Order B')
    order_a=row(('mushroom','olive'),1.3,(-3.5,.1,0),.7)
    order_b=row(('olive','pepper'),1.3,(3.5,.1,0),.7)
    scene.play(FadeIn(a,b,order_a,order_b),run_time=1.2)
    cue(scene,t,14)
    replace_text(scene,head,heading('Buy everything on either order'),run_time=.6)
    cap=change(scene,None,'UNION  ·  either order counts',cfg.GREEN)
    cue(scene,t,25)
    scene.play(FadeOut(a,b),order_a[0].animate.move_to([-2.5,.2,0]),order_a[1].animate.move_to([0,.2,0]),order_b[0].animate.move_to([0,.2,0]),order_b[1].animate.move_to([2.5,.2,0]),run_time=1.5)
    scene.remove(order_b[0])
    plate=tray(9.5,2.8,cfg.GREEN,[0,.2,0]); scene.play(FadeIn(plate),run_time=.6)
    cap=change(scene,cap,'Each topping appears once',cfg.GREEN)
    cue(scene,t,39)
    math=formula('A ∪ B = {mushroom, olive, pepper}',44,cfg.GREEN).move_to([0,2.65,0])
    scene.play(FadeIn(math),run_time=.8); cue(scene,t,48)
    clear(scene,head)
    replace_text(scene,head,heading('What did both friends choose?'),run_time=.6)
    belt=conveyor(); scene.play(FadeIn(belt),run_time=.7)
    gates=VGroup(tray(2.1,2.7,cfg.BLUE,[-1.8,-.4,0],'On order A?'),tray(2.1,2.7,cfg.ORANGE,[1.8,-.4,0],'On order B?'))
    scene.play(FadeIn(gates),run_time=.8)
    cap=change(scene,None,'INTERSECTION  ·  both must say yes',cfg.GOLD)
    cue(scene,t,61)
    for name,in_a,in_b,mark in [('mushroom',True,False,75),('pepper',False,True,86),('olive',True,True,102)]:
        item=food(name,1.05,[-5.6,-1.5,0]); scene.play(FadeIn(item),run_time=.4)
        scene.play(item.animate.move_to([-1.8,-1.5,0]),run_time=.9)
        first=checkmark([-1.8,.3,0]) if in_a else label('×',46,cfg.RED).move_to([-1.8,.3,0])
        scene.play(FadeIn(first),run_time=.5)
        second=None
        if in_a:
            scene.play(item.animate.move_to([1.8,-1.5,0]),run_time=.9)
            second=checkmark([1.8,.3,0]) if in_b else label('×',46,cfg.RED).move_to([1.8,.3,0])
            scene.play(FadeIn(second),run_time=.5)
        destination=[5.6,-1.5,0] if in_a and in_b else [5.6,1.4,0]
        scene.play(item.animate.move_to(destination).set_opacity(1 if in_a and in_b else .35),run_time=.8)
        cue(scene,t,mark)
        scene.play(FadeOut(item,first,*([second] if second is not None else [])),run_time=.5)
    clear(scene,head)
    replace_text(scene,head,heading('Collect from either. Keep what is shared.'),run_time=.6)
    union_food=row(('mushroom','olive','pepper'),1.1,(-3.5,0,0),.4)
    shared=food('olive',1.4,[3.5,0,0])
    equations=VGroup(formula('A ∪ B',52,cfg.GREEN).move_to([-3.5,1.7,0]),formula('A ∩ B = {olive}',46,cfg.GOLD).move_to([3.5,1.7,0]))
    scene.play(FadeIn(union_food,shared,equations),run_time=.8)
    cap=change(scene,None,'If nothing is shared, A ∩ B = ∅')
    cue(scene,t,123.5)
    math_beat(scene,head,'The two membership rules',['x\\in A\\cup B\\;\\Longleftrightarrow\\;(x\\in A)\\lor(x\\in B)', 'x\\in A\\cap B\\;\\Longleftrightarrow\\;(x\\in A)\\land(x\\in B)'],'Union: either. Intersection: both.')
    cue(scene,t,141.5)
    end_scene(scene,t,cfg.SCENE_DURATIONS['06']); finish(scene)
